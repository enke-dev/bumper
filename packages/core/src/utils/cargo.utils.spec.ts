const REGISTRY = 'registry+https://github.com/rust-lang/crates.io-index';

// keep the user's own `$CARGO_HOME/config.toml` out of the gate under test
process.env['CARGO_HOME'] = join(tmpdir(), 'bumper-spec-no-cargo-home');

// verbatim from cargo 1.100 under `registry.global-min-publish-age` (the crate renamed)
const TOO_NEW = [
  'error: failed to select a version for the requirement `tauri-plugin-http = "^2"`',
  '  version 2.9.0 is too new (published 2 days ago, minimum age 7 days)',
  'location searched: crates.io index',
  'help: to use too-new packages anyways, re-resolve with `CARGO_RESOLVER_INCOMPATIBLE_PUBLISH_AGE=allow`',
].join('\n');

// verbatim from cargo 1.100, `--precise` below the manifest's requirement (paths shortened)
const UNMET = [
  'error: failed to select a version for the requirement `tauri-plugin-opener = "^2.5"`',
  "candidate versions found which didn't match: 2.4.0",
  'location searched: crates.io index',
  'required by package `b v0.1.0 (/tmp/b)`',
].join('\n');

const PLAIN = { CARGO_TERM_COLOR: 'never', CARGO_TERM_QUIET: 'false' };

/** A `Cargo.lock` body from `[name, version, source?]` entries. */
function lockfile(crates: [string, string, string?][]): string {
  const blocks = crates.map(
    ([name, version, source]) =>
      `[[package]]\nname = "${name}"\nversion = "${version}"\n${source ? `source = "${source}"\n` : ''}`
  );
  return `# This file is automatically @generated by Cargo.\nversion = 4\n\n${blocks.join('\n')}`;
}

const ok = (stdout: string): ExecResult => ({ exitCode: 0, stdout, stderr: '' });

describe('parseCargoLock', () => {
  test('reads every package, telling registry crates from path ones', () => {
    const crates = parseCargoLock(
      lockfile([
        ['app', '0.1.0'],
        ['serde', '1.0.228', REGISTRY],
      ])
    );
    assert.deepEqual(crates, [
      { name: 'app', version: '0.1.0', registry: false, cratesIo: false },
      { name: 'serde', version: '1.0.228', registry: true, cratesIo: true },
    ]);
  });
});

describe('diffCargoLock', () => {
  test('lists moved registry crates, pairing several versions of one name in order', () => {
    const before = lockfile([
      ['app', '0.1.0'],
      ['tokio', '1.53.2', REGISTRY],
      ['windows-sys', '0.52.0', REGISTRY],
      ['windows-sys', '0.59.0', REGISTRY],
      ['gone', '1.0.0', REGISTRY],
    ]);
    const after = lockfile([
      ['app', '0.2.0'],
      ['tokio', '1.53.3', REGISTRY],
      ['windows-sys', '0.52.0', REGISTRY],
      ['windows-sys', '0.59.1', REGISTRY],
      ['new', '1.0.0', REGISTRY],
    ]);
    assert.deepEqual(diffCargoLock(before, after), [
      { name: 'tokio', from: '1.53.2', to: '1.53.3' },
      { name: 'windows-sys', from: '0.59.0', to: '0.59.1' },
    ]);
  });
});

describe('diffCargoLock across majors', () => {
  test('a major gone away is no move to another major', () => {
    const before = lockfile([
      ['syn', '1.0.1', REGISTRY],
      ['syn', '2.0.1', REGISTRY],
    ]);
    const after = lockfile([['syn', '2.0.2', REGISTRY]]);
    assert.deepEqual(diffCargoLock(before, after), [{ name: 'syn', from: '2.0.1', to: '2.0.2' }]);
  });

  test('below 1.0 each minor is a line of its own, below 0.1 each patch', () => {
    const before = lockfile([
      ['windows-sys', '0.52.0', REGISTRY],
      ['windows-sys', '0.59.0', REGISTRY],
      ['tiny', '0.0.3', REGISTRY],
    ]);
    const after = lockfile([
      ['windows-sys', '0.59.1', REGISTRY],
      ['windows-sys', '0.60.0', REGISTRY],
      ['tiny', '0.0.4', REGISTRY],
    ]);
    assert.deepEqual(diffCargoLock(before, after), [
      { name: 'windows-sys', from: '0.59.0', to: '0.59.1' },
    ]);
  });
});

describe('setsCratesIoPublishAge', () => {
  test("finds the crates.io age in each spelling, not another registry's", () => {
    assert.equal(setsCratesIoPublishAge('[registry]\nglobal-min-publish-age = "7 days"'), true);
    assert.equal(setsCratesIoPublishAge('registry.global-min-publish-age = "7 days"'), true);
    assert.equal(setsCratesIoPublishAge('[registries.crates-io]\nmin-publish-age = "1 day"'), true);
    assert.equal(setsCratesIoPublishAge('[registries.private]\nmin-publish-age = "1 day"'), false);
    assert.equal(setsCratesIoPublishAge('# global-min-publish-age = "7 days"'), false);
  });

  test('reads quoted names, inline tables and trailing comments', () => {
    assert.equal(
      setsCratesIoPublishAge('[registries."crates-io"]\nmin-publish-age = "1 day"'),
      true
    );
    assert.equal(
      setsCratesIoPublishAge('[ registry ]\n\'global-min-publish-age\' = "7 days"'),
      true
    );
    assert.equal(setsCratesIoPublishAge('registry = { global-min-publish-age = "7 days" }'), true);
    assert.equal(
      setsCratesIoPublishAge('registries = { crates-io = { min-publish-age = "1 day" } }'),
      true
    );
    assert.equal(
      setsCratesIoPublishAge(
        '[registries]\ncrates-io = { index = "x", min-publish-age = "1 day" }'
      ),
      true
    );
    assert.equal(
      setsCratesIoPublishAge('[registries]\nprivate = { min-publish-age = "1 day" } # crates-io'),
      false
    );
    assert.equal(
      setsCratesIoPublishAge('[registry]\ntoken = "a#b" # global-min-publish-age = "7 days"'),
      false
    );
    // a later table ends the one before
    assert.equal(
      setsCratesIoPublishAge('[registry]\n[[bin]]\nglobal-min-publish-age = "7 days"'),
      false
    );
  });
});

describe('tooNewCrate', () => {
  test('names the crate a cooldown refusal is about, null for other failures', () => {
    assert.equal(tooNewCrate(TOO_NEW), 'tauri-plugin-http');
    assert.equal(tooNewCrate('error: failed to load manifest'), null);
    assert.equal(tooNewCrate(UNMET), null);
  });
});

describe('unmetRequirement', () => {
  test('names the requirement a precise version falls outside of, null for other failures', () => {
    assert.equal(unmetRequirement(UNMET), 'tauri-plugin-opener = "^2.5"');
    assert.equal(unmetRequirement(TOO_NEW), null);
  });
});

describe('parseCargoUpdate', () => {
  test('reads no moves from colored output, which the plain output env rules out', () => {
    const colored = '\u001b[1m\u001b[92m    Updating\u001b[0m serde v1.0.200 -> v1.0.229';
    assert.deepEqual(parseCargoUpdate(colored), { updates: [], downgrades: [] });
  });

  test('splits the moves into updates and downgrades', () => {
    // verbatim from cargo 1.100 under `registry.global-min-publish-age`
    const log = [
      '    Updating crates.io index',
      '     Locking 2 packages to highest compatible versions as of 38 days ago',
      ' Downgrading pin-project-lite v0.2.18 -> v0.2.17 (available: v0.2.18, published 5 days ago)',
      '    Updating tokio v1.53.2 -> v1.53.3 (available: v1.54.1, published 34 days ago)',
      'warning: not updating lockfile due to dry run',
    ].join('\n');
    assert.deepEqual(parseCargoUpdate(log), {
      updates: [{ name: 'tokio', from: '1.53.2', to: '1.53.3' }],
      downgrades: [{ name: 'pin-project-lite', from: '0.2.18', to: '0.2.17' }],
    });
  });
});

