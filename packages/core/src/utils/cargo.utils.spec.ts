describe('cargoGate', () => {
  test('carries the cooldown to cargo, or nothing without one', async () => {
    await withTempDir('cargo-gate', async dir => {
      const ctx = contextFor(dir);
      assert.deepEqual(await cargoGate(ctx, dir), { env: PLAIN, gated: false });
      const gated = await cargoGate(ctx, dir, { ...NO_RELEASE_AGE, seconds: 86400 });
      assert.deepEqual(gated, {
        env: { ...PLAIN, CARGO_REGISTRY_GLOBAL_MIN_PUBLISH_AGE: '86400 seconds' },
        gated: true,
      });
    });
  });

  test('a publish age the repo configures for cargo wins', async () => {
    await withTempDir('cargo-gate', async dir => {
      const crateDir = join(dir, 'src-tauri');
      await mkdir(join(dir, '.cargo'), { recursive: true });
      await mkdir(crateDir);
      await writeFile(
        join(dir, '.cargo', 'config.toml'),
        '[registry]\nglobal-min-publish-age = "7 days"\n'
      );
      const gate = await cargoGate(contextFor(dir), crateDir, { ...NO_RELEASE_AGE, seconds: 60 });
      assert.deepEqual(gate, { env: PLAIN, gated: true });
    });
  });

  test('a publish age set in the environment wins', async () => {
    await withTempDir('cargo-gate', async dir => {
      process.env['CARGO_REGISTRIES_CRATES_IO_MIN_PUBLISH_AGE'] = '14 days';
      try {
        const gate = await cargoGate(contextFor(dir), dir, { ...NO_RELEASE_AGE, seconds: 60 });
        assert.deepEqual(gate, { env: PLAIN, gated: true });
      } finally {
        delete process.env['CARGO_REGISTRIES_CRATES_IO_MIN_PUBLISH_AGE'];
      }
    });
  });

  test("a publish age in the user's cargo home wins", async () => {
    await withTempDir('cargo-gate', async dir => {
      const home = process.env['CARGO_HOME'];
      process.env['CARGO_HOME'] = join(dir, 'cargo-home');
      try {
        await mkdir(join(dir, 'cargo-home'));
        await writeFile(
          join(dir, 'cargo-home', 'config.toml'),
          '[registries.crates-io]\nmin-publish-age = "3 days"\n'
        );
        const gate = await cargoGate(contextFor(dir), dir, { ...NO_RELEASE_AGE, seconds: 60 });
        assert.deepEqual(gate, { env: PLAIN, gated: true });
      } finally {
        process.env['CARGO_HOME'] = home;
      }
    });
  });
});

describe('assertPublishAgeSupport', () => {
  test('needs a cargo that enforces the publish age', async () => {
    await assertPublishAgeSupport(async () => ok('cargo 1.100.0 (3acc79c0c 2026-11-05)\n'));
    await assert.rejects(
      assertPublishAgeSupport(async () => ok('cargo 1.99.1 (5f94df478 2026-08-27)\n')),
      /cargo 1\.99\.1 ignores the release age/
    );
    await assert.rejects(
      assertPublishAgeSupport(async () => {
        throw new Error('spawn cargo ENOENT');
      }),
      /cargo not found/
    );
  });
});

describe('findCargoDirs', () => {
  test('takes lockfiles beside a manifest, honoring excludes', async () => {
    await withTempDir('cargo-dirs', async dir => {
      const crate = async (path: string, manifest: boolean) => {
        await mkdir(join(dir, path), { recursive: true });
        await writeFile(join(dir, path, 'Cargo.lock'), lockfile([]));
        if (manifest) {
          await writeFile(join(dir, path, 'Cargo.toml'), '[package]\nname = "x"\n');
        }
      };
      await crate('src-tauri', true);
      await crate('fixtures/stray', false);
      await crate('vendor/other', true);
      const dirs = await findCargoDirs(contextFor(dir, false, ['vendor']));
      assert.deepEqual(dirs, [join(dir, 'src-tauri')]);
    });
  });
});
